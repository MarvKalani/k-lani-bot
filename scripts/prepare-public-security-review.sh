#!/usr/bin/env bash
set -euo pipefail
umask 077
ulimit -c 0
repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd "$repo_root"
: "${K_LANI_BOT_SYFT:?Supply the pinned development Syft binary}"
: "${K_LANI_BOT_GRYPE:?Supply the pinned development Grype binary}"

# This packet must identify committed source, not a mixture of edited files.
git diff --quiet && git diff --cached --quiet || { printf 'Commit the reviewed source before preparing a public release packet.\n' >&2; exit 2; }
[[ -z "$(git ls-files --others --exclude-standard)" ]] || { printf 'Untracked source must be reviewed and committed first.\n' >&2; exit 2; }
source_commit=$(git rev-parse HEAD)
packet_parent="$repo_root/.artifacts/public-security-review/$source_commit"
final_packet="$packet_parent/core-linux-x11"
[[ ! -e "$final_packet" ]] || { printf 'An immutable review packet already exists for this commit.\n' >&2; exit 2; }
mkdir -p "$packet_parent"
packet=$(mktemp -d "$packet_parent/.candidate.XXXXXXXX")
candidate="$packet/candidate"
evidence="$packet/review"
mkdir -p "$candidate" "$evidence"
review_project="$repo_root/tools/k-lani-bot-release-review/k-lani-bot-release-review.csproj"
run_check() {
    local step_id=$1
    shift
    local exit_code=0
    "$@" > "$evidence/$step_id.log" 2>&1 || exit_code=$?
    dotnet run --project "$review_project" --verbosity quiet -- record "$evidence" "$step_id" "$exit_code" "$source_commit" "$evidence/$step_id.log"
    [[ "$exit_code" == 0 ]] || { printf 'Release check failed: %s. Review its private log.\n' "$step_id" >&2; exit "$exit_code"; }
    printf 'Passed: %s\n' "$step_id"
}
run_check format scripts/format.sh --check
# check.sh executes the full warnings-as-errors build once before any test.
# Preserve that actual transcript as the separate build evidence instead of
# repeating the same build merely to produce another step record.
run_check regression scripts/check.sh
cp .artifacts/all-project-builds.log "$evidence/build.log"
dotnet run --project "$review_project" --verbosity quiet -- record "$evidence" build 0 "$source_commit" "$evidence/build.log"
run_check repository-guard scripts/repository-guard.sh --mode history --ref "$source_commit"
run_check gitleaks scripts/gitleaks.sh history "$source_commit"

dotnet publish src/k-lani-bot-node/k-lani-bot-node.csproj -c Release -f net10.0 -r linux-x64 \
    -p:TargetFrameworks=net10.0 -p:DebugType=None -p:DebugSymbols=false -p:ContinuousIntegrationBuild=true \
    "-p:PathMap=$repo_root=/_/src" -warnaserror --nologo -o "$candidate" > "$evidence/publish.log" 2>&1
cp LICENSE.md "$candidate/LICENSE.md"
cp docs/legal/OPERATOR-SAFETY.md "$candidate/OPERATOR-SAFETY.md"
# Preserve the dependency descriptor generated by this exact publish for SBOM
# cataloguers; the single-file executable does not depend on this sidecar.
cp src/k-lani-bot-node/bin/Release/net10.0/linux-x64/k-lani-bot-node.deps.json "$candidate/k-lani-bot-node.deps.json"
dotnet run --project "$review_project" --verbosity quiet -- notices \
    src/k-lani-bot-node/obj/project.assets.json "$candidate/THIRD-PARTY-NOTICES.txt"
cp .release/public-security-profile.json "$evidence/profile.json"

docker build -f docker/Dockerfile.node -t k-lani-bot-actuator:local . > "$evidence/container-build.log" 2>&1
image_id=$(docker image inspect k-lani-bot-actuator:local --format '{{.Id}}')
printf '%s\n' "$image_id" > "$evidence/container-image-id.txt"
# Run the exact candidate inside the worker with its complete desktop dependencies. A host without wmctrl must not
# silently skip native compact Info in a package acceptance. The self-contained test driver needs no SDK in that image.
probe="$evidence/transport-probe"
dotnet publish tests/TransportRegression/TransportRegression.csproj -c Release -r linux-x64 --self-contained true \
    -p:PublishSingleFile=true -p:IncludeNativeLibrariesForSelfExtract=true -warnaserror --nologo -o "$probe" \
    > "$evidence/transport-probe-publish.log" 2>&1
run_check binary-transport docker run --rm --network none --read-only --cap-drop ALL --security-opt no-new-privileges \
    --pids-limit 512 --ulimit core=0:0 --user "$(id -u):$(id -g)" --tmpfs /tmp:rw,nosuid,size=768m \
    --mount "type=bind,src=$probe,dst=/probe,readonly" \
    --mount "type=bind,src=$candidate,dst=/candidate,readonly" \
    --mount "type=bind,src=$repo_root/contracts,dst=/workspace/contracts,readonly" \
    --mount "type=bind,src=$repo_root/scripts/private-gui-session.sh,dst=/private-gui-session.sh,readonly" \
    --mount "type=bind,src=$repo_root/scripts/private-window-manager.sh,dst=/private-window-manager.sh,readonly" \
    --env HOME=/tmp/probe-home --entrypoint /private-gui-session.sh "$image_id" \
    /private-window-manager.sh /probe/TransportRegression /candidate/k-lani-bot-node
run_check binary-sandbox dotnet run --project tests/SandboxRegression/SandboxRegression.csproj --verbosity quiet -- "$candidate/k-lani-bot-node"
[[ "$(docker image inspect k-lani-bot-actuator:local --format '{{.Id}}')" == "$image_id" ]] || { printf 'Worker image changed during acceptance.\n' >&2; exit 2; }
run_check binary-supply-chain scripts/supply-chain-check.sh "$candidate" "$evidence/binary-security"
run_check container-supply-chain scripts/supply-chain-check.sh "$image_id" "$evidence/container-security"

git diff --quiet && git diff --cached --quiet && [[ "$(git rev-parse HEAD)" == "$source_commit" ]] || { printf 'Source changed during acceptance.\n' >&2; exit 2; }
dotnet run --project "$review_project" --verbosity quiet -- assess "$candidate" "$evidence/profile.json" "$evidence" "$evidence/assessment.json"
mv "$packet" "$final_packet"
printf 'Candidate and private evidence prepared in %s\n' "$final_packet"
printf 'Alpha candidate is technically ready with declared limits; independent certification and publication have not occurred.\n'
