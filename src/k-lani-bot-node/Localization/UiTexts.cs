// Use case: the person at the machine reads the tray menu, the consent dialog and the activity banner in their own
// language. The administrator sets the language when the node is set up; without that the system language decides,
// German for German and English for everything else. It is chosen once when the visible worker starts.
// UiTextCases checks that both tables name every text.
public static class UiTexts
{
    public static UiLanguage Language { get; private set; } = SystemLanguage();

    // Every process that builds desktop texts calls this once with the node's setting, so they all speak alike.
    public static void Use(UiLanguage? configured)
    {
        Language = configured ?? SystemLanguage();
    }

    public static UiLanguage SystemLanguage()
    {
        return CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "de" ? UiLanguage.German : UiLanguage.English;
    }

    public static string Get(UiText text)
    {
        return TableOf(Language)[text];
    }

    public static string Format(UiText text, params object[] arguments)
    {
        return string.Format(CultureInfo.InvariantCulture, Get(text), arguments);
    }

    public static IReadOnlyDictionary<UiText, string> TableOf(UiLanguage language)
    {
        return language == UiLanguage.German ? German : English;
    }

